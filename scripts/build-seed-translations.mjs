/**
 * Builds src/content/seedTranslations.generated.ts from
 * chapters/*.txt + meta.json (titles).
 *
 * Run: npx tsx scripts/build-seed-translations.mjs
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const chaptersDir = join(root, "src/content/chapters");
const meta = JSON.parse(
  readFileSync(join(chaptersDir, "meta.json"), "utf8"),
);

const LOCALES = ["ca", "es", "en", "fr"];

const rows = [];

for (const chapter of meta) {
  const id = String(chapter.id).padStart(2, "0");
  for (const locale of LOCALES) {
    const path = join(chaptersDir, `${id}.${locale}.txt`);
    let content;
    try {
      content = readFileSync(path, "utf8").replace(/\r\n/g, "\n").trimEnd() + "\n";
    } catch {
      throw new Error(`Missing chapter body: ${path}`);
    }
    const titleKey = `title_${locale}`;
    const title = chapter[titleKey];
    if (!title) throw new Error(`Missing ${titleKey} for chapter ${chapter.id}`);
    rows.push({
      reflection_id: String(chapter.id),
      language: locale,
      title,
      content,
    });
  }
}

const outPath = join(root, "src/content/seedTranslations.generated.ts");
const header = `/* eslint-disable */
/** Generated by scripts/build-seed-translations.mjs — do not edit by hand. */

export type SeedTranslation = {
  reflection_id: string;
  language: "ca" | "es" | "en" | "fr";
  title: string;
  content: string;
};

export const seedTranslations: SeedTranslation[] = [
`;

const body = rows
  .map(
    (row) => `  {
    reflection_id: ${JSON.stringify(row.reflection_id)},
    language: ${JSON.stringify(row.language)},
    title: ${JSON.stringify(row.title)},
    content: ${JSON.stringify(row.content)},
  }`,
  )
  .join(",\n");

writeFileSync(outPath, `${header}${body},\n];\n`, "utf8");
console.log(
  `Wrote ${outPath} (${rows.length} rows, ${meta.length} chapters × ${LOCALES.length} locales)`,
);

// Sanity: no locale should equal Catalan for the same chapter
let sameAsCa = 0;
for (const chapter of meta) {
  const ca = rows.find(
    (r) => r.reflection_id === String(chapter.id) && r.language === "ca",
  );
  for (const locale of ["es", "en", "fr"]) {
    const row = rows.find(
      (r) => r.reflection_id === String(chapter.id) && r.language === locale,
    );
    if (row && ca && row.content === ca.content) {
      sameAsCa += 1;
      console.warn(
        `WARN: chapter ${chapter.id} ${locale} body still identical to Catalan`,
      );
    }
  }
}
if (sameAsCa === 0) console.log("OK: all ES/EN/FR bodies differ from Catalan");
