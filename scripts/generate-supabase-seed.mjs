/**
 * Generates supabase/seed.sql from src/content/seed.ts
 * Run: node --experimental-strip-types scripts/generate-supabase-seed.mjs
 * Or: npx tsx scripts/generate-supabase-seed.mjs
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const seedPath = join(root, "src/content/seed.ts");

const { reflectionRecords, reflectionTranslations } = await import(
  pathToFileURL(seedPath).href
);

function dollarQuote(value) {
  let tag = "c";
  while (value.includes(`$${tag}$`)) tag += "x";
  return `$${tag}$${value}$${tag}$`;
}

function sqlLiteral(value) {
  if (value == null) return "NULL";
  return dollarQuote(String(value));
}

const lines = [
  "-- Generated by scripts/generate-supabase-seed.mjs — do not edit by hand",
  "truncate table public.reflection_translations cascade;",
  "truncate table public.reflections cascade;",
  "",
];

for (const r of reflectionRecords) {
  lines.push(
    `insert into public.reflections (id, slug, "order", type, status, image) values (${sqlLiteral(r.id)}, ${sqlLiteral(r.slug)}, ${r.order}, ${sqlLiteral(r.type)}, ${sqlLiteral(r.status)}, ${sqlLiteral(r.image ?? null)});`,
  );
}

lines.push("");

for (const t of reflectionTranslations) {
  lines.push(
    `insert into public.reflection_translations (id, reflection_id, language, title, content) values (${sqlLiteral(t.id)}, ${sqlLiteral(t.reflection_id)}, ${sqlLiteral(t.language)}, ${sqlLiteral(t.title)}, ${sqlLiteral(t.content)});`,
  );
}

lines.push("");

const out = join(root, "supabase/seed.sql");
writeFileSync(out, lines.join("\n"), "utf8");
console.log(`Wrote ${out} (${reflectionRecords.length} reflections, ${reflectionTranslations.length} translations)`);
